#!/usr/bin/env bash
# Pixel-art Clawd living in his room on a waybar custom module.
# What he does depends on what's happening on screen, highest priority first:
#   battery low or CPU hot            -> turns red
#   no input for CLAWD_IDLE seconds   -> sleeps by the bed
#   Claude Code working or CPU busy   -> progress bar, at the desk
#   video playing                     -> popcorn
#   terminal or editor focused        -> codes at the desk
#   browser or document focused       -> reads
#   messenger focused                 -> chats
#   music playing                     -> headphones
#   otherwise                         -> hangs around, plays now and then
# Short reactions play on top: notifications, a long shell command finishing
# (ok / fail), Claude Code finishing a task, and hearts on click (SIGUSR1).
# Frames, positions and stations come from clawd.css (see gen.py).

DIR=$(dirname "$(readlink -f "$0")")
DELAY=${CLAWD_DELAY:-0.083}    # 12 fps, like the emoji pack
IDLE_AFTER=${CLAWD_IDLE:-60}
CPU_BUSY=${CLAWD_CPU_BUSY:-80}
BATTERY_LOW=${CLAWD_BATTERY_LOW:-15}
CPU_HOT=${CLAWD_CPU_HOT:-90}
CODE_APPS=${CLAWD_CODE_APPS:-'^(kitty|Alacritty|foot|org\.wezfurlong\.wezterm|com\.mitchellh\.ghostty|[Cc]ode|code-oss|[Cc]odium|VSCodium|jetbrains-.*|dev\.zed\.Zed)$'}
READ_APPS=${CLAWD_READ_APPS:-'^(firefox|zen|librewolf|floorp|[Cc]hromium|google-chrome|brave-browser|vivaldi-stable|org\.qutebrowser\.qutebrowser|org\.pwmt\.zathura|evince|org\.gnome\.Evince|okular|org\.kde\.okular|obsidian)$'}
CHAT_APPS=${CLAWD_CHAT_APPS:-'^(org\.telegram\.desktop|telegram-desktop|TelegramDesktop|discord|vesktop|signal|Signal|Slack|Element|whatsapp.*)$'}
VIDEO_PLAYERS='^(mpv|vlc|celluloid|totem|haruna|smplayer)'
BROWSER_PLAYERS='^(firefox|chromium|chrome|brave|zen|librewolf|vivaldi)'

# stations and frame counts as generated by gen.py: home=56 ... n-code=12 ...
declare -A AT
for kv in $(sed -n 's|.*clawd: \(.*\) \*/.*|\1|p' "$DIR/clawd.css"); do
    AT[${kv%%=*}]=${kv#*=}
done
declare -A STATION=([code]=desk [busy]=desk [ok]=desk [fail]=desk [sleep]=bed)
EXTRAS=(happy skate ball trumpet)
# demo tour on right click (SIGUSR2): every animation in turn
DEMO=(code busy ok fail read chat music video alert notify done happy skate ball trumpet love sleep)

# events from outside (hooks/) arrive as files in $RUN
RUN=${XDG_RUNTIME_DIR:-/tmp}/clawd
mkdir -p "$RUN"
rm -f "$RUN"/idle "$RUN"/ev-*

trap 'pkill -P $$' EXIT
trap 'exit' TERM INT HUP

# idle detection through a private hypridle instance
cat > "$RUN/hypridle.conf" <<EOF
general {
    ignore_dbus_inhibit = true
    ignore_systemd_inhibit = true
    inhibit_sleep = 0
}
listener {
    timeout = $IDLE_AFTER
    on-timeout = touch $RUN/idle
    on-resume = rm -f $RUN/idle
}
EOF
pkill -f "hypridle -q -c $RUN/hypridle.conf"
hypridle -q -c "$RUN/hypridle.conf" &

# notifications, whichever daemon shows them
pkill -f '^clawd-notify'
(exec -a clawd-notify dbus-monitor --session "type='method_call',interface='org.freedesktop.Notifications',member='Notify'" 2>/dev/null) |
    {
        # clicks signal every process named clawd.sh, this subshell included
        trap '' USR1 USR2
        while read -r line; do
            [[ $line == *member=Notify* ]] && : > "$RUN/ev-notify"
        done
    } &

BAT=$(ls -d /sys/class/power_supply/BAT* 2>/dev/null | head -1)
TEMP=
for h in /sys/class/hwmon/hwmon*; do
    [[ $(< "$h/name") =~ ^(k10temp|coretemp|zenpower|cpu_thermal)$ ]] && { TEMP=$h/temp1_input; break; }
done

cpu_total=0
cpu_idle=0
cpu_load=0
cpu() {
    # smoothed CPU load in percent since the previous call
    local _ user nice sys idle iowait irq softirq steal total idle_all
    read -r _ user nice sys idle iowait irq softirq steal _ < /proc/stat
    total=$(( user + nice + sys + idle + iowait + irq + softirq + steal ))
    idle_all=$(( idle + iowait ))
    if (( cpu_total && total > cpu_total )); then
        cpu_load=$(( (100 - 100 * (idle_all - cpu_idle) / (total - cpu_total) + 2 * cpu_load) / 3 ))
    fi
    cpu_total=$total
    cpu_idle=$idle_all
}

hot() {
    local cap state t
    if [[ -n $BAT ]]; then
        read -r cap < "$BAT/capacity"
        read -r state < "$BAT/status"
        [[ $state == Discharging ]] && (( cap <= BATTERY_LOW )) && return 0
    fi
    if [[ -n $TEMP ]]; then
        read -r t < "$TEMP"
        (( t >= CPU_HOT * 1000 )) && return 0
    fi
    return 1
}

claude_busy() {
    # refreshed by Claude Code hooks; stale after 5 minutes in case Stop never came
    [[ -e $RUN/claude-busy ]] && (( EPOCHSECONDS - $(stat -c %Y "$RUN/claude-busy") < 300 ))
}

pick_mood() {
    local class status name video=0 music=0
    class=$(hyprctl activewindow -j | jq -r '.class // empty')
    while read -r status name; do
        [[ $status == Playing ]] || continue
        if [[ $name =~ $VIDEO_PLAYERS ]] || { [[ $name =~ $BROWSER_PLAYERS ]] && [[ $class =~ $READ_APPS ]]; }; then
            video=1
        else
            music=1
        fi
    done < <(playerctl -a metadata --format '{{status}} {{playerName}}' 2>/dev/null)
    cpu

    if hot; then new=alert
    elif [[ -e $RUN/idle ]] && (( !video && !music )); then new=sleep
    elif claude_busy || (( cpu_load >= CPU_BUSY )); then new=busy
    elif (( video )); then new=video
    elif [[ $class =~ $CODE_APPS ]]; then new=code
    elif [[ $class =~ $READ_APPS ]]; then new=read
    elif [[ $class =~ $CHAT_APPS ]]; then new=chat
    elif (( music )); then new=music
    else new=idle
    fi
}

# one-shot animation over the current mood, looped for about 3 seconds
shot=
shot_i=0
shot_len=0
play() {
    local n=${AT[n-$1]}
    shot=$1
    shot_i=0
    shot_len=$(( (36 + n - 1) / n * n ))
}

mood=idle
i=0
tick=0
look=0     # idle frame while not blinking: 0 rest, 2 left, 3 right
blink=0

demo=-1
demo_i=0
demo_len=0

demo_at() {
    # start demo item $1, looped for about 2.5 seconds
    local n=${AT[n-${DEMO[$1]}]}
    demo=$1
    demo_i=0
    demo_len=$(( (30 + n - 1) / n * n ))
}

demo_step() {
    # sets frame and pos while the demo runs; false once it's over
    (( demo < 0 )) && return 1
    if (( demo_i >= demo_len )); then
        (( demo + 1 >= ${#DEMO[@]} )) && { demo=-1; return 1; }
        demo_at $(( demo + 1 ))
    fi
    frame=${DEMO[demo]}-$(( demo_i % AT[n-${DEMO[demo]}] ))
    pos=${AT[${STATION[${DEMO[demo]}]:-home}]}
    (( demo_i++ ))
}

trap 'play love' USR1
trap 'demo_at 0' USR2

while :; do
    if (( tick % 12 == 0 )); then
        pick_mood
        [[ $new != "$mood" ]] && { mood=$new; i=0; }
        for ev in notify ok fail done; do
            if [[ -e $RUN/ev-$ev ]]; then
                rm -f "$RUN/ev-$ev"
                play "$ev"
                break
            fi
        done
    fi
    (( tick++ ))

    pos=${AT[${STATION[$mood]:-home}]}
    tip=${shot:-$mood}
    if demo_step; then
        tip="demo: ${DEMO[demo]}"
    elif [[ -n $shot ]]; then
        frame=$shot-$(( shot_i % AT[n-$shot] ))
        (( ++shot_i >= shot_len )) && shot=
    elif [[ $mood == idle ]]; then
        # mostly still, blinking and glancing around, now and then playing
        if (( blink > 0 )); then
            frame=idle-1
            (( blink-- ))
        else
            frame=idle-$look
            (( RANDOM % 50 == 0 )) && blink=2
            if (( RANDOM % 80 == 0 )); then
                looks=(0 0 2 3)
                look=${looks[RANDOM % 4]}
            fi
            (( RANDOM % 540 == 0 )) && play "${EXTRAS[RANDOM % ${#EXTRAS[@]}]}"
        fi
    else
        frame=$mood-$(( i % AT[n-$mood] ))
        (( i++ ))
    fi

    printf '{"text":" ","tooltip":"Clawd: %s","class":["f-%s","p-%d"]}\n' "$tip" "$frame" "$pos"

    sleep "$DELAY" & wait $!
done
